#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
node saturn/benchmarks/generate-fixtures.cjs
node saturn/benchmarks/compile-results.cjs
node saturn/benchmarks/compile-model-results.cjs
node saturn/benchmarks/compile-math-results.cjs
# clang + lld, no emscripten, npm bundle, libc, CDN, or web framework needed.
"${CLANG:-clang}" --target=wasm32 -O3 -std=c11 -ffreestanding -fno-builtin \
  -fno-fast-math -ffp-contract=off -nostdlib -DSH2Z_FORCE_PORTABLE=1 \
  -Isaturn/include exhibits/bridge.c saturn/src/*.c \
  -Wl,--no-entry -Wl,--export-memory -Wl,--initial-memory=4194304 \
  -Wl,--max-memory=4194304 -Wl,-z,stack-size=65536 \
  -o exhibits/math.wasm
# A self-contained JS loader also works from a downloaded index.html over file://.
python3 - <<'PY'
import base64, hashlib, json, pathlib
p=pathlib.Path('exhibits/math.wasm')
b=p.read_bytes()
pathlib.Path('exhibits/math-module.js').write_text(
    '// Generated by build.sh from the actual SH2ZAM C sources. Do not edit.\n'
    'window.SH2ZAM_WASM_BASE64='+json.dumps(base64.b64encode(b).decode())+';\n'
    'window.SH2ZAM_WASM_SHA256='+json.dumps(hashlib.sha256(b).hexdigest())+';\n')
PY
cp doc/sh2zam-gainz.webp exhibits/gainz.webp
cp LICENSE exhibits/LICENSE
cp NOTICE.md exhibits/NOTICE.md
printf 'Built exhibits/math.wasm and self-contained loader. Open exhibits/index.html.\n'

