/* Generate exact browser Q16 vertex inputs and loop poses. MIT. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {makeMesh}=require('../../exhibits/meshes.js');
const cases=[];
for(const scene of ['saturn','cubes','torus'])for(let detail=1;detail<=5;detail++){
  const mesh=makeMesh(scene,detail);
  cases.push({scene,detail,vertices:mesh.vertices.map(v=>Math.round(v*65536))});
}
const poses=Array.from({length:21},(_,i)=>{
  const phase=i/21,ax=Math.round(5200+3000*Math.sin(phase*Math.PI*2))&65535,ay=Math.floor(phase*65536)&65535;
  return {ax,ay,trig:[Math.sin(ax*Math.PI*2/65536),Math.cos(ax*Math.PI*2/65536),Math.sin(ay*Math.PI*2/65536),Math.cos(ay*Math.PI*2/65536)].map(Math.fround)};
});
const sha=crypto.createHash('sha256').update(JSON.stringify({cases,poses})).digest('hex');
let h='/* Generated by generate-fixtures.cjs. Do not edit. */\n#include "sh2zam/sh2zam.h"\n#define FIXTURE_SHA "'+sha+'"\n#define CASE_COUNT 15\n#define SAMPLE_COUNT 21\n';
for(let k=0;k<cases.length;k++){
  const c=cases[k];h+=`static const sh2z_vec3_t mesh_${k}[]={\n`;
  for(let i=0;i<c.vertices.length;i+=3)h+='{'+c.vertices.slice(i,i+3).join(',')+'},\n';h+='};\n';
}
h+='static const struct {const char *scene; unsigned detail,count; const sh2z_vec3_t *vertices;} cases[]={\n';
cases.forEach((c,k)=>h+=`{"${c.scene}",${c.detail},${c.vertices.length/3},mesh_${k}},\n`);h+='};\n';
h+='static const struct {unsigned ax,ay; float sx,cx,sy,cy;} poses[]={\n';
poses.forEach(p=>h+=`{${p.ax},${p.ay},${p.trig.map(x=>x.toExponential(9)+'f').join(',')}},\n`);h+='};\n';
fs.writeFileSync(path.join(__dirname,'fixtures.h'),h);
fs.writeFileSync(path.join(__dirname,'manifest.json'),JSON.stringify({schema:1,fixtureSHA256:sha,poses:21,cases:cases.map(c=>({scene:c.scene,detail:c.detail,vertices:c.vertices.length/3}))},null,2)+'\n');
console.log('Fixture SHA256:',sha);
